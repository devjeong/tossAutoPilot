/** 중복 심볼 제거 */
const UNIQUE_MASTER: KrMasterItem[] = (() => {
  const m = new Map<string, string>()
  for (const it of KR_STOCK_MASTER) {
    if (!m.has(it.symbol)) m.set(it.symbol, it.name)
  }
  return [...m.entries()].map(([symbol, name]) => ({ symbol, name }))
})()

export function searchKrMaster(query: string, limit = 20): KrMasterItem[] {
  const q = query.trim().toLowerCase()
  if (!q) return []

  const scored: { item: KrMasterItem; score: number }[] = []
  for (const item of UNIQUE_MASTER) {
    const name = item.name.toLowerCase()
    const sym = item.symbol
    let score = 0
    if (name === q) score = 100
    else if (name.startsWith(q)) score = 80
    else if (name.includes(q)) score = 60
    else if (sym === q || sym.startsWith(q)) score = 70
    else if (sym.includes(q)) score = 40
    else continue
    scored.push({ item, score })
  }
  scored.sort((a, b) => b.score - a.score || a.item.name.localeCompare(b.item.name, 'ko'))
  return scored.slice(0, limit).map((s) => s.item)
}
